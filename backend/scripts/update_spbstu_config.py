PARAMS = {"study_form": "Очная", "finance_type": "Бюджетная основа"}


def build_majors() -> list[dict]:
    return [
        {"code": code, "name": name, "params": PARAMS.copy()}
        for code, name in SPBSTU_MAJORS
    ]


def main() -> None:
    config_path = Path(__file__).resolve().parents[1] / "config.json"
    data = json.loads(config_path.read_text(encoding="utf-8"))

    for uni in data["universities"]:
        if uni["code"] == "SPBSTU":
            old_count = len(uni["majors"])
            uni["majors"] = build_majors()
            print(f"SPBSTU majors: {old_count} -> {len(uni['majors'])}")
            break
    else:
        raise SystemExit("SPBSTU not found in config.json")

    config_path.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    load_config(config_path)
    print("config.json updated and validated")


if __name__ == "__main__":
    main()
